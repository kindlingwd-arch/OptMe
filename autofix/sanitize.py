# 把 Gemini 给的改写提示词里会触发 MiniMax 审核（new_sensitive）的词去掉或换成温和说法
import re
RULES = [
    (r"(脸上|额头|嘴角|身上)?(带着?|有|满是|挂着?)?(明显的?|一道道?|几道)?(血迹|血痕|伤痕|淤伤|淤青|伤口|血污)+(的)?[、，]?", ""),
    (r"满脸是血", "满脸疲惫"), (r"鲜血|流血|血", ""),
    (r"受伤|伤", ""), (r"打斗|殴打|打架", "推搡"), (r"往死里削|削", ""),
    (r"抢劫|被抢", "出事"), (r"劫匪|抢匪", "嫌疑人"), (r"手枪|枪|刀子|刀", ""),
    (r"挣扎", "扭动"), (r"押解|押着", "带着"),
]
def clean(text):
    t = text or ""
    for a, b in RULES: t = re.sub(a, b, t)
    t = re.sub(r"[、，]{2,}", "，", t); t = re.sub(r"，。", "。", t)
    t = re.sub(r"(带|有)的", "", t); t = re.sub(r"、(年轻|小伙|男子)", r"的\1", t)
    return t.strip("，、 ")
def bad_words(text):
    return [w for w in ("血", "伤", "打斗", "抢劫", "劫匪", "削", "枪", "刀") if w in (text or "")]
if __name__ == "__main__":
    for s in ["后座戴狗皮帽、脸上带血痕的年轻人直视女人并张嘴回话", "车门打开，脸上带明显血迹伤痕、戴狗皮帽穿破旧棉袄的小伙弯腰扒着车门", "民警押解身穿破旧棉袄的年轻男子，被押男子回头挣扎求救"]:
        print(clean(s), bad_words(clean(s)))

const { contextBridge, ipcRenderer, webUtils } = require("electron");
const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a).then(r => { if (!r.ok) throw new Error(r.error); return r.data; });
contextBridge.exposeInMainWorld("studio", {
  recent: () => call("project:recent"),
  pickProject: () => call("project:pick"),
  load: dir => call("project:load", dir),
  files: dir => call("project:files", dir),
  save: (dir, data) => call("project:save", dir, data),
  replace: (dir, rel, src) => call("asset:replace", dir, rel, src),
  pickAsset: kind => call("asset:pick", kind),
  importFiles: (dir, paths) => call("asset:import", dir, paths),
  readAsset: (dir, rel) => call("asset:read", dir, rel),
  writeAsset: (dir, rel, bytes) => call("asset:write", dir, rel, bytes),
  exportGame: (dir, name) => call("game:export", dir, name),
  saveText: (name, text) => call("file:saveText", name, text),
  reveal: p => call("shell:reveal", p),
  openPath: p => call("shell:open", p),
  imgPath: src => call("img:path", src),
  copyImage: src => call("img:copy", src),
  copyText: t => call("img:copyText", t),
  saveImageAs: src => call("img:saveAs", src),
  confirm: (msg, buttons) => call("app:confirm", msg, buttons),
  refocus: () => call("app:refocus"),
  close: () => call("app:close"),
  sbLoad: dir => call("sb:load", dir),
  sbSaveShot: (dir, shot) => call("sb:saveShot", dir, shot),
  sbReview: (dir, sid, ok, note, mtime, extra) => call("sb:review", dir, sid, ok, note, mtime, extra),
  sbReviewMany: (dir, entries) => call("sb:reviewMany", dir, entries),
  sketchWrite: (dir, rel, data, isB64) => call("sketch:write", dir, rel, data, isB64),
  sketchRead: (dir, rel) => call("sketch:read", dir, rel),
  vsLoad: dir => call("vs:load", dir),
  vsSave: (dir, id, patch) => call("vs:save", dir, id, patch),
  vsAdd: (dir, list) => call("vs:add", dir, list),
  vsDel: (dir, id) => call("vs:del", dir, id),
  refsLoad: dir => call("refs:load", dir),
  voiceRefsLoad: dir => call("voiceRefs:load", dir),
  voiceRefsSave: (dir, entry) => call("voiceRefs:save", dir, entry),
  voiceRefsImport: (dir, id, src) => call("voiceRefs:import", dir, id, src),
  voiceRefsGenerate: (dir, id, action, text) => call("voiceRefs:generate", dir, id, action, text),
  refsSave: (dir, entry) => call("refs:save", dir, entry),
  refsImport: (dir, id, src) => call("refs:import", dir, id, src),
  refPath: (dir, rel) => call("sb:refUrl", dir, rel),
  runTool: (dir, script, args) => call("tool:run", dir, script, args),
  stopTool: id => call("tool:stop", id),
  onToolLog: fn => ipcRenderer.on("tool:log", (_e, d) => fn(d)),      // d = { id, text }
  onToolDone: fn => ipcRenderer.on("tool:done", (_e, d) => fn(d)),    // d = { id, code }
  filePath: f => (webUtils && webUtils.getPathForFile) ? webUtils.getPathForFile(f) : f.path,
  onMenu: fn => ipcRenderer.on("menu", (_e, cmd) => fn(cmd)),
  onBeforeClose: fn => ipcRenderer.on("app:before-close", () => fn()),
  platform: process.platform,
});
